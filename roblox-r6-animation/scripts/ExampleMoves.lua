local function ss(t, a, b)
	local u = math.clamp((t - a) / (b - a), 0, 1)
	return u * u * (3 - 2 * u)
end

local L0 = {-0.45, -0.35, 5}
local L1 = {-0.6, -0.85, -10}

local function rfoot(t)
	return {0.55, 0.45, -25 + 30 * ss(t, 0.53, 0.66) - 30 * ss(t, 1.2, 1.45)}
end

local function lfoot(t)
	local a = math.clamp((t - 0.3) / 0.15, 0, 1)
	local b = math.clamp((t - 1.2) / 0.25, 0, 1)
	local u = ss(t, 0.3, 0.45) - ss(t, 1.2, 1.45)
	local lift = 0.3 * math.sin(math.pi * a) + 0.2 * math.sin(math.pi * b)
	local yaw = L0[3] + (L1[3] - L0[3]) * u + 30 * ss(t, 0.53, 0.62) - 30 * ss(t, 1.2, 1.45)
	return {L0[1] + (L1[1] - L0[1]) * u, L0[2] + (L1[2] - L0[2]) * u, yaw, lift}
end

local function knee(t)
	local u = ss(t, 0.95, 1.25)
	local a = math.clamp((t - 0.95) / 0.3, 0, 1)
	local z = 0.3 + 1.5 * ss(t, 0, 0.05) + (0.35 - 1.8) * u
	local b = math.clamp(t / 0.05, 0, 1)
	return {0.6, z, -10, 0.3 * math.sin(math.pi * a) + 0.25 * math.sin(math.pi * b)}
end

local function leapFoot(stand, wide)
	return function(t)
		if t > 0.17 and t < 0.70 then
			return nil
		end
		if t <= 0.17 then
			return stand
		end
		local u = ss(t, 0.95, 1.15)
		return {wide[1] + (stand[1] - wide[1]) * u, wide[2] + (stand[2] - wide[2]) * u, wide[3] + (stand[3] - wide[3]) * u, 0.15 * math.sin(math.pi * u)}
	end
end

